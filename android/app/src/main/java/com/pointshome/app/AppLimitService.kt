package com.pointshome.app

import android.accessibilityservice.AccessibilityService
import android.app.KeyguardManager
import android.content.Context
import android.content.Intent
import android.content.IntentFilter
import android.content.BroadcastReceiver
import android.graphics.Color
import android.graphics.PixelFormat
import android.graphics.Typeface
import android.graphics.drawable.GradientDrawable
import android.os.PowerManager
import android.os.SystemClock
import android.view.Gravity
import android.view.View
import android.view.WindowManager
import android.view.accessibility.AccessibilityEvent
import android.widget.Button
import android.widget.LinearLayout
import android.widget.TextView
import android.widget.ScrollView
import androidx.core.view.ViewCompat
import androidx.core.view.WindowInsetsCompat
import androidx.core.content.ContextCompat
import kotlinx.coroutines.*
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.asStateFlow
import kotlinx.coroutines.flow.collect
import kotlinx.coroutines.channels.Channel

class AppLimitService : AccessibilityService() {
    private val scope = CoroutineScope(SupervisorJob() + Dispatchers.IO.limitedParallelism(1))
    private val changes = Channel<Unit>(Channel.CONFLATED)
    private var counting = false
    private var screenReceiverRegistered = false
    private val screenReceiver = object : BroadcastReceiver() {
        override fun onReceive(context: Context, intent: Intent) {
            if (intent.action == Intent.ACTION_SCREEN_OFF && ::budget.isInitialized) {
                val offAt = SystemClock.uptimeMillis()
                scope.launch {
                    budget.pause(offAt)
                    liveMillis.value = budget.availableMillis()
                    withContext(Dispatchers.Main) { hideBlock() }
                }
            }
            changes.trySend(Unit)
        }
    }
    private lateinit var store: LocalControlStore
    private lateinit var budget: TimeBudget
    @Volatile private var foreground = ""
    @Volatile private var overlayShown = false
    private var overlay: View? = null
    private var previousPackages = emptySet<String>()
    private var previousSuspended: Boolean? = null
    private var owner = false
    private var ownerCheckedAt = 0L
    @Volatile private var inputMethods = emptySet<String>()
    private var inputMethodsCheckedAt = 0L

    override fun onServiceConnected() {
        store = LocalControlStore.get(this)
        // Uptime excludes deep sleep, so waking a sleeping phone cannot consume hours of game time.
        budget = TimeBudget({ store.snapshot().remainingMillis }, store::adjustRemainingMillis, SystemClock::uptimeMillis)
        ContextCompat.registerReceiver(this, screenReceiver, IntentFilter().apply {
            addAction(Intent.ACTION_SCREEN_OFF); addAction(Intent.ACTION_SCREEN_ON)
        },
            ContextCompat.RECEIVER_NOT_EXPORTED)
        screenReceiverRegistered = true
        owner = ControlAdmin.isOwner(this)
        inputMethods = ControlAdmin.inputMethodPackages(this)
        connected.value = true
        scope.launch { store.state.collect { changes.trySend(Unit) } }
        scope.launch {
            while (isActive) {
                try { tick() }
                catch (cancel: CancellationException) { throw cancel }
                catch (_: Exception) {
                    problem.value = "本机管控暂时异常，请家长检查权限与设置"
                    if (owner) runCatching { ControlAdmin.suspend(this@AppLimitService, store.snapshot().packages, true) }
                    if (store.snapshot().enabled && foreground in store.snapshot().packages)
                        withContext(Dispatchers.Main) { runCatching { showBlock() } }
                }
                withTimeoutOrNull(if (counting) 250L else 1_000L) { changes.receive() }
            }
        }
    }
    override fun onAccessibilityEvent(event: AccessibilityEvent?) {
        if (event?.eventType != AccessibilityEvent.TYPE_WINDOW_STATE_CHANGED) return
        val name = event.packageName?.toString() ?: return
        // The keyboard overlays the current app; it must not turn game usage into free time.
        if (name in inputMethods) return
        // Events generated by our blocking window must not masquerade as leaving the blocked app.
        if (overlayShown && name == packageName) return
        if (foreground != name) { foreground = name; changes.trySend(Unit) }
    }
    private suspend fun tick() {
        if (SystemClock.elapsedRealtime() - inputMethodsCheckedAt >= 30_000) {
            inputMethods = ControlAdmin.inputMethodPackages(this)
            inputMethodsCheckedAt = SystemClock.elapsedRealtime()
        }
        if (SystemClock.elapsedRealtime() - ownerCheckedAt >= 3_000) {
            val nextOwner = ControlAdmin.isOwner(this)
            if (nextOwner != owner) previousSuspended = null
            owner = nextOwner; ownerCheckedAt = SystemClock.elapsedRealtime()
        }
        val state = store.snapshot()
        val interactive = (getSystemService(Context.POWER_SERVICE) as PowerManager).isInteractive
            && !(getSystemService(Context.KEYGUARD_SERVICE) as KeyguardManager).isKeyguardLocked
        val limited = state.enabled && foreground in state.packages && interactive
        counting = limited
        val allowed = if (limited) budget.resume() else { budget.pause(); true }
        liveMillis.value = budget.availableMillis()
        if (owner) {
            val suspended = state.enabled && budget.availableMillis() <= 0
            if (state.packages != previousPackages || suspended != previousSuspended) {
                ControlAdmin.suspend(this, previousPackages - state.packages, false)
                val failures = ControlAdmin.suspend(this, state.packages, suspended)
                problem.value = if (failures.isEmpty()) null else "${failures.size} 个应用不支持系统暂停，请调整受限列表"
                previousPackages = state.packages
                previousSuspended = suspended
            }
        }
        withContext(Dispatchers.Main) {
            if (limited && !allowed) showBlock() else hideBlock()
        }
    }
    private fun showBlock() {
        if (overlay != null) return
        val density = resources.displayMetrics.density
        fun dp(n: Int) = (density * n).toInt()
        val root = ScrollView(this).apply {
            isFillViewport = true; setBackgroundColor(Color.rgb(244, 248, 245))
        }
        val body = LinearLayout(this).apply {
            orientation = LinearLayout.VERTICAL; gravity = Gravity.CENTER
            setPadding(dp(24), dp(24), dp(24), dp(24))
        }
        ViewCompat.setOnApplyWindowInsetsListener(root) { _, insets ->
            val safe = insets.getInsets(WindowInsetsCompat.Type.systemBars() or WindowInsetsCompat.Type.displayCutout())
            body.setPadding(dp(24) + safe.left, dp(24) + safe.top, dp(24) + safe.right, dp(24) + safe.bottom)
            insets
        }
        val card = LinearLayout(this).apply {
            orientation = LinearLayout.VERTICAL; gravity = Gravity.CENTER_HORIZONTAL
            setPadding(dp(24), dp(30), dp(24), dp(30))
            background = GradientDrawable().apply { setColor(Color.WHITE); cornerRadius = dp(28).toFloat() }
        }
        card.addView(android.widget.ImageView(this).apply {
            setImageResource(R.mipmap.ic_launcher)
            layoutParams = LinearLayout.LayoutParams(dp(64), dp(64)).apply { bottomMargin = dp(16) }
        })
        fun text(value: String, size: Float, bold: Boolean = false) = TextView(this).apply {
            text = value; textSize = size; gravity = Gravity.CENTER; setTextColor(Color.rgb(33, 59, 56))
            setPadding(0, 0, 0, dp(20)); if (bold) typeface = Typeface.DEFAULT_BOLD
        }
        card.addView(text("先兑换一点时间", 26f, true))
        card.addView(text("可用时间已用完\n在积分小屋兑换并请家长批准后，就能继续使用。", 16f))
        fun button(label: String, action: () -> Unit) = Button(this).apply {
            text = label; isAllCaps = false; setTextColor(Color.WHITE)
            background = android.graphics.drawable.RippleDrawable(
                android.content.res.ColorStateList.valueOf(Color.argb(40, 255, 255, 255)),
                GradientDrawable().apply { setColor(Color.rgb(39, 104, 94)); cornerRadius = dp(16).toFloat() }, null)
            setOnClickListener { action() }
            minimumHeight = dp(56)
            layoutParams = LinearLayout.LayoutParams(-1, -2).apply { topMargin = dp(10) }
        }
        card.addView(button("前往积分小屋兑换") {
            hideBlock(); foreground = packageName
            startActivity(Intent(this, MainActivity::class.java).putExtra("open_page", "app_time")
                .addFlags(Intent.FLAG_ACTIVITY_NEW_TASK or Intent.FLAG_ACTIVITY_CLEAR_TOP or Intent.FLAG_ACTIVITY_SINGLE_TOP))
        })
        card.addView(button("返回桌面") { hideBlock(); foreground = ""; performGlobalAction(GLOBAL_ACTION_HOME) })
        body.addView(card, LinearLayout.LayoutParams(dp(440).coerceAtMost(resources.displayMetrics.widthPixels - dp(48)), -2))
        root.addView(body, android.widget.FrameLayout.LayoutParams(-1, -2))
        root.isFocusableInTouchMode = true
        root.setOnKeyListener { _, code, event ->
            if (code == android.view.KeyEvent.KEYCODE_BACK && event.action == android.view.KeyEvent.ACTION_UP) {
                hideBlock(); foreground = ""; performGlobalAction(GLOBAL_ACTION_HOME); true
            } else false
        }
        val params = WindowManager.LayoutParams(-1, -1, WindowManager.LayoutParams.TYPE_ACCESSIBILITY_OVERLAY,
            WindowManager.LayoutParams.FLAG_LAYOUT_IN_SCREEN, PixelFormat.TRANSLUCENT)
        params.gravity = Gravity.CENTER
        (getSystemService(Context.WINDOW_SERVICE) as WindowManager).addView(root, params)
        overlay = root; overlayShown = true
    }
    private fun hideBlock() {
        overlay?.let { runCatching { (getSystemService(Context.WINDOW_SERVICE) as WindowManager).removeView(it) } }
        overlay = null; overlayShown = false
    }
    override fun onInterrupt() { foreground = "" }
    override fun onConfigurationChanged(newConfig: android.content.res.Configuration) {
        super.onConfigurationChanged(newConfig)
        if (overlay != null) {
            // Recompute the card width and safe padding after rotation, density or font changes.
            hideBlock(); showBlock()
        }
    }
    override fun onDestroy() {
        if (screenReceiverRegistered) runCatching { unregisterReceiver(screenReceiver) }
        scope.cancel(); connected.value = false; hideBlock()
        if (::budget.isInitialized) CoroutineScope(Dispatchers.IO).launch {
            runCatching { budget.pause() }
            runCatching { if (store.snapshot().enabled) ControlAdmin.suspend(this@AppLimitService, store.snapshot().packages, true) }
        }
        super.onDestroy()
    }
    companion object {
        private val connected = MutableStateFlow(false)
        val running = connected.asStateFlow()
        private val liveMillis = MutableStateFlow(0L)
        val remaining = liveMillis.asStateFlow()
        val problem = MutableStateFlow<String?>(null)
    }
}
